await dlg().waitFor();
console.log('1 open', url(), 'dialogs', await page.getByRole('dialog').count(), 'focus-inside', await page.evaluate(()=>!!document.activeElement.closest('[role=dialog]')), 'hist+', (await page.evaluate(()=>history.length))-n0);
await page.keyboard.press('Escape'); await dlg().waitFor({state:'detached'});
console.log('2 esc', url());
await page.getByRole('button',{name:'메뉴'}).click();
await page.getByRole('dialog',{name:'메뉴'}).locator('button[type=button]').first().click(); await dlg().waitFor();
